"""Build the CSS token distribution from the canonical JSON file."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent
tokens = json.loads((root / 'tokens.json').read_text(encoding='utf-8'))
lines = ['/* Generated by build_tokens.py. Edit tokens.json instead. */', ':root {']
for group, values in tokens.items():
    lines.extend(f'  --{group}-{name}: {value};' for name, value in values.items())
lines.append('}')
(root / 'tokens.css').write_text('\n'.join(lines) + '\n', encoding='utf-8')
